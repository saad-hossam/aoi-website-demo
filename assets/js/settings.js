  function getStored(key, fallback) {
    try { const v = localStorage.getItem(key); return v == null ? fallback : v; }
    catch (e) { return fallback; }
  }
  function setStored(key, value) {
    try { localStorage.setItem(key, value); } catch (e) { /* noop */ }
  }

  function swapBootstrap(dir) {
    const link = document.getElementById('bootstrap-css');
    if (!link) return;
    const target = dir === 'rtl' ? BOOTSTRAP_RTL : BOOTSTRAP_LTR;
    if (link.href !== target) link.href = target;
  }

  function applyTranslations(lang) {
    const dict = translations[lang] || translations.ar;

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      const key = el.getAttribute('data-i18n');
      if (dict[key] != null) el.textContent = dict[key];
    });

    // data-i18n-placeholder support for form fields
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key] != null) el.setAttribute('placeholder', dict[key]);
    });

    // Dispatch for dynamically-rendered content
    document.dispatchEvent(new CustomEvent('aoi:language', { detail: { lang: lang, dict: dict } }));

    // Title per-page fallback
    if (!document.documentElement.dataset.pageTitleFixed) {
      document.title = lang === 'ar'
        ? 'الهيئة العربية للتصنيع | Arab Organization for Industrialization'
        : 'Arab Organization for Industrialization | الهيئة العربية للتصنيع';
    }
  }

  function applyLanguage(lang) {
    const safeLang = lang === 'en' ? 'en' : 'ar';
    const dir = safeLang === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.setAttribute('lang', safeLang);
    document.documentElement.setAttribute('dir', dir);
    swapBootstrap(dir);
    applyTranslations(safeLang);
    const label = document.getElementById('lang-toggle-label');
    if (label) label.textContent = safeLang === 'ar' ? 'EN' : 'عربي';
    setStored(STORAGE_LANG, safeLang);
    // refresh palette label language
    syncPaletteUI(getStored(STORAGE_PALETTE, 'copper'));
  }

  function applyTheme(theme) {
    const safeTheme = theme === 'dark' ? 'dark' : 'light';
    document.documentElement.setAttribute('data-theme', safeTheme);
    setStored(STORAGE_THEME, safeTheme);
  }

  function applyPalette(palette) {
    const safe = PALETTES.indexOf(palette) >= 0 ? palette : 'copper';
    document.documentElement.setAttribute('data-palette', safe);
    setStored(STORAGE_PALETTE, safe);
    syncPaletteUI(safe);
  }

  function syncPaletteUI(palette) {
    document.querySelectorAll('.palette-option').forEach(function (btn) {
      const isActive = btn.getAttribute('data-palette') === palette;
      btn.classList.toggle('is-active', isActive);
      btn.setAttribute('aria-pressed', isActive ? 'true' : 'false');
    });
    const label = document.getElementById('palette-label');
    if (label) {
      const lang = getStored(STORAGE_LANG, 'ar');
      const names = PALETTE_LABELS[palette] || PALETTE_LABELS.copper;
      label.textContent = names[lang] || names.en;
    }
    const title = document.getElementById('palette-panel-title');
    if (title) {
      title.textContent = getStored(STORAGE_LANG, 'ar') === 'ar' ? 'ألوان الموقع' : 'Site colors';
    }
  }

  function openPalettePanel() {
    const panel = document.getElementById('palette-panel');
    const fab = document.getElementById('palette-fab');
    if (!panel) return;
    panel.hidden = false;
    if (fab) fab.setAttribute('aria-expanded', 'true');
    document.body.style.overflow = 'hidden';
    const closeBtn = panel.querySelector('.palette-panel__close');
    if (closeBtn) closeBtn.focus();
  }

  function closePalettePanel() {
    const panel = document.getElementById('palette-panel');
    const fab = document.getElementById('palette-fab');
    if (!panel) return;
    panel.hidden = true;
    if (fab) {
      fab.setAttribute('aria-expanded', 'false');
      fab.focus();
    }
    document.body.style.overflow = '';
  }

  function initPalettePicker() {
    const fab = document.getElementById('palette-fab');
    const panel = document.getElementById('palette-panel');
    if (!fab || !panel) return;

    fab.addEventListener('click', function (e) {
      e.stopPropagation();
      openPalettePanel();
    });

    panel.querySelectorAll('[data-palette-close]').forEach(function (el) {
      el.addEventListener('click', function () { closePalettePanel(); });
    });

    panel.querySelectorAll('.palette-option').forEach(function (btn) {
      btn.addEventListener('click', function () {
        applyPalette(btn.getAttribute('data-palette'));
        closePalettePanel();
      });
    });

    document.addEventListener('keydown', function (e) {
      if (e.key === 'Escape' && panel && !panel.hidden) {
        closePalettePanel();
      }
    });
  }

  window.AOISettings = {
    getLanguage: function () { return getStored(STORAGE_LANG, 'ar'); },
    setLanguage: applyLanguage,
    toggleLanguage: function () {
      applyLanguage(this.getLanguage() === 'ar' ? 'en' : 'ar');
    },
    getTheme: function () { return getStored(STORAGE_THEME, 'light'); },
    setTheme: applyTheme,
    getPalette: function () { return getStored(STORAGE_PALETTE, 'copper'); },
    setPalette: applyPalette,
    getPalettes: function () { return PALETTES.slice(); },
    // expose dictionary for page modules
    getDict: function () { return translations[this.getLanguage()] || translations.ar; }
  };

  document.addEventListener('DOMContentLoaded', function () {
    applyLanguage(getStored(STORAGE_LANG, 'ar'));
    applyTheme(getStored(STORAGE_THEME, 'light'));
    applyPalette(getStored(STORAGE_PALETTE, 'copper'));
    initPalettePicker();
    const btn = document.getElementById('lang-toggle');
    if (btn) btn.addEventListener('click', function () { window.AOISettings.toggleLanguage(); });
  });
